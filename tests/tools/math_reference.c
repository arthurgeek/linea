/* Offline MPFR reference generation, independent of the shipped runtime. */
#undef NDEBUG
#include <assert.h>
#include <inttypes.h>
#include <math.h>
#include <mpfr.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

static uint64_t encoding(double value) {
    uint64_t bits;
    memcpy(&bits, &value, sizeof bits);
    return bits;
}

static double number(uint64_t bits) {
    double value;
    memcpy(&value, &bits, sizeof value);
    return value;
}

static int apply(unsigned operation, mpfr_ptr result, mpfr_srcptr input, mpfr_srcptr exponent,
                 mpfr_rnd_t direction) {
    switch (operation) {
    case 0: return mpfr_sqrt(result, input, direction);
    case 1: return mpfr_rint(result, input, MPFR_RNDD);
    case 2: return mpfr_rint(result, input, MPFR_RNDU);
    case 3: return mpfr_rint(result, input, MPFR_RNDZ);
    case 4: return mpfr_rint(result, input, MPFR_RNDN);
    case 5: return mpfr_sin(result, input, direction);
    case 6: return mpfr_cos(result, input, direction);
    case 7: return mpfr_log(result, input, direction);
    case 8: return mpfr_exp(result, input, direction);
    case 9: return mpfr_pow(result, input, exponent, direction);
    default: assert(0); return 0;
    }
}

static uint64_t canonical(double result) {
    return isnan(result) ? UINT64_C(0x7ff8000000000000) : encoding(result);
}

static uint64_t reference(unsigned operation, uint64_t input, uint64_t exponent) {
    mpfr_t x, y, result;
    mpfr_inits2(53, x, y, result, (mpfr_ptr)0);
    assert(mpfr_set_emin(-1073) == 0);
    assert(mpfr_set_emax(1024) == 0);
    mpfr_set_d(x, number(input), MPFR_RNDN);
    mpfr_set_d(y, number(exponent), MPFR_RNDN);
    int inexact = apply(operation, result, x, y, MPFR_RNDN);
    mpfr_subnormalize(result, inexact, MPFR_RNDN);
    uint64_t expected = canonical(mpfr_get_d(result, MPFR_RNDN));
    mpfr_clears(x, y, result, (mpfr_ptr)0);
    return expected;
}

/* Directed enclosures independently confirm transcendental finite samples.
   Precision grows until both bounds round to the same binary64 encoding. */
static void confirm(unsigned operation, uint64_t input, uint64_t exponent, uint64_t expected) {
    if (operation < 5 || (expected & UINT64_C(0x7ff0000000000000)) ==
                            UINT64_C(0x7ff0000000000000)) return;
    assert(mpfr_set_emin(MPFR_EMIN_DEFAULT) == 0);
    assert(mpfr_set_emax(MPFR_EMAX_DEFAULT) == 0);
    for (mpfr_prec_t precision = 128; precision <= 16384; precision *= 2) {
        mpfr_t x, y, lower, upper;
        mpfr_inits2(precision, x, y, lower, upper, (mpfr_ptr)0);
        mpfr_set_d(x, number(input), MPFR_RNDN);
        mpfr_set_d(y, number(exponent), MPFR_RNDN);
        apply(operation, lower, x, y, MPFR_RNDD);
        apply(operation, upper, x, y, MPFR_RNDU);
        uint64_t lo = canonical(mpfr_get_d(lower, MPFR_RNDN));
        uint64_t hi = canonical(mpfr_get_d(upper, MPFR_RNDN));
        mpfr_clears(x, y, lower, upper, (mpfr_ptr)0);
        if (lo == hi) {
            assert(lo == expected);
            return;
        }
    }
    fprintf(stderr, "unresolved oracle: operation %u input %016" PRIx64 "\n",
            operation, input);
    assert(0);
}

static void emit_pair(unsigned operation, uint64_t input, uint64_t exponent) {
    uint64_t expected = reference(operation, input, exponent);
    confirm(operation, input, exponent, expected);
    printf("    {%u, UINT64_C(0x%016" PRIx64 "), UINT64_C(0x%016" PRIx64 "), UINT64_C(0x%016" PRIx64 ")},\n",
           operation, input, exponent, expected);
}

static void emit(unsigned operation, uint64_t input) {
    emit_pair(operation, input, 0);
}

int main(void) {
    const uint64_t landmarks[] = {
        0, 1, 2, UINT64_C(0x000fffffffffffff), UINT64_C(0x0010000000000000),
        UINT64_C(0x0010000000000001), UINT64_C(0x3fdfffffffffffff),
        UINT64_C(0x3fe0000000000000), UINT64_C(0x3fe0000000000001),
        UINT64_C(0x3fefffffffffffff), UINT64_C(0x3ff0000000000000),
        UINT64_C(0x3ff0000000000001), UINT64_C(0x3ff921fb54442d18),
        UINT64_C(0x4000000000000000), UINT64_C(0x4004000000000000),
        UINT64_C(0x400921fb54442d18), UINT64_C(0x400c000000000000),
        UINT64_C(0x432fffffffffffff), UINT64_C(0x4330000000000000),
        UINT64_C(0x4330000000000001), UINT64_C(0x4340000000000000),
        UINT64_C(0x7feffffffffffffe), UINT64_C(0x7fefffffffffffff),
        UINT64_C(0x7ff0000000000000), UINT64_C(0x7ff8000000000000),
    };
    printf("/* Generated by tests/tools/math_reference.c with MPFR %s. */\n", mpfr_get_version());
    printf("static const struct math_vector math_vectors[] = {\n");
    for (unsigned op = 0; op < 9; ++op) {
        for (unsigned i = 0; i < sizeof landmarks / sizeof landmarks[0]; ++i) {
            emit(op, landmarks[i]);
            emit(op, landmarks[i] | UINT64_C(0x8000000000000000));
        }
        /* Fixed xorshift stream samples signs, exponents and significands. */
        uint64_t state = UINT64_C(0xd1b54a32d192ed03);
        for (unsigned i = 0; i < 512; ++i) {
            state ^= state << 13;
            state ^= state >> 7;
            state ^= state << 17;
            if ((state & UINT64_C(0x7ff0000000000000)) != UINT64_C(0x7ff0000000000000))
                emit(op, state);
        }
    }
    /* Neighbors of exp overflow/underflow and trigonometric reduction points. */
    const uint64_t centers[] = {
        UINT64_C(0x40862e42fefa39ef), UINT64_C(0xc0874910d52d3051),
        UINT64_C(0x3ff921fb54442d18), UINT64_C(0x400921fb54442d18),
        UINT64_C(0x401921fb54442d18),
    };
    for (unsigned op = 5; op < 9; ++op)
        for (unsigned i = 0; i < sizeof centers / sizeof centers[0]; ++i)
            for (uint64_t offset = 0; offset < 17; ++offset)
                emit(op, centers[i] - 8 + offset);
    /* Powers cover identities, exponent parity and the full magnitude range. */
    const uint64_t exponents[] = {
        0, UINT64_C(0x8000000000000000), 1, UINT64_C(0x3fe0000000000000),
        UINT64_C(0x3ff0000000000000), UINT64_C(0x4000000000000000),
        UINT64_C(0x4008000000000000), UINT64_C(0x408ff80000000000),
        UINT64_C(0x432fffffffffffff), UINT64_C(0x433fffffffffffff),
        UINT64_C(0x4340000000000000), UINT64_C(0x7ff0000000000000),
        UINT64_C(0x7ff8000000000000),
    };
    for (unsigned i = 0; i < sizeof landmarks / sizeof landmarks[0]; ++i)
        for (unsigned j = 0; j < sizeof exponents / sizeof exponents[0]; ++j)
            for (unsigned signs = 0; signs < 4; ++signs)
                emit_pair(9, landmarks[i] | ((uint64_t)(signs & 1) << 63),
                          exponents[j] | ((uint64_t)(signs >> 1) << 63));
    printf("};\n");
    return ferror(stdout) ? 1 : 0;
}
